package io.tebex.minecraft.platform;

/**
 * The PlatformType enum represents the different server platforms supported by the Tebex Tebex
 * runtime. The current supported platforms include Bukkit, BungeeCord, Velocity, Fabric, NeoForge,
 * Forge, and Folia.
 */
public enum PlatformType {
  BUKKIT,
  BUNGEECORD,
  VELOCITY,
  FABRIC,
  NEOFORGE,
  FORGE,
  FOLIA,
}
